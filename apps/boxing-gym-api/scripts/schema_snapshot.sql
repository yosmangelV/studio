-- Read-only snapshot of the `public` schema, built from the system catalogs.
--
-- Used instead of `pg_dump --schema-only` because pg_dump refuses servers newer
-- than itself, while psql connects to any version. Output is deterministic
-- (everything is ordered by name) so the file diffs cleanly between runs.
--
-- Run through scripts/dump_schema.sh; never edit schema/public.sql by hand.

\set ON_ERROR_STOP on
set default_transaction_read_only = on;
set search_path = '';

-- Objects created by extensions are not ours to snapshot. Inlined as a psql
-- variable because a read-only session cannot create even a temp view.
\set own_objects '(select c.oid, c.relname, c.relkind from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = \'public\' and not exists (select 1 from pg_depend d where d.classid = \'pg_class\'::regclass and d.objid = c.oid and d.deptype = \'e\'))'

\echo '-- Generated by scripts/dump_schema.sh. Do not edit by hand.'
\echo '-- Source of truth for what is deployed; migrations/ must converge to this.'
\echo ''

\echo '-- ── Extensions ──────────────────────────────────────────────'
select format('-- extension %s (schema %s)', e.extname, n.nspname)
from pg_extension e join pg_namespace n on n.oid = e.extnamespace
where e.extname <> 'plpgsql'
order by e.extname;
\echo ''

\echo '-- ── Enum types ──────────────────────────────────────────────'
select format('create type public.%I as enum (%s);', t.typname,
       string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder))
from pg_type t
join pg_namespace n on n.oid = t.typnamespace
join pg_enum e on e.enumtypid = t.oid
where n.nspname = 'public'
group by t.typname
order by t.typname;
\echo ''

\echo '-- ── Tables ──────────────────────────────────────────────────'
select format(E'create table public.%I (\n%s\n);\n', o.relname,
       string_agg(
         format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                case when a.attnotnull then ' not null' else '' end,
                coalesce(' default ' || pg_get_expr(ad.adbin, ad.adrelid), '')),
         E',\n' order by a.attnum))
from :own_objects o
join pg_attribute a on a.attrelid = o.oid and a.attnum > 0 and not a.attisdropped
left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
where o.relkind in ('r', 'p')
group by o.relname
order by o.relname;

\echo '-- ── Constraints ─────────────────────────────────────────────'
select format('alter table public.%I add constraint %I %s;', o.relname, con.conname,
       pg_get_constraintdef(con.oid))
from pg_constraint con
join :own_objects o on o.oid = con.conrelid
where con.contype in ('p', 'u', 'f', 'c', 'x')
order by o.relname, position(con.contype in 'pucfx'), con.conname;
\echo ''

\echo '-- ── Indexes (not backing a constraint) ──────────────────────'
select pg_get_indexdef(i.indexrelid) || ';'
from pg_index i
join :own_objects o on o.oid = i.indrelid
join pg_class ic on ic.oid = i.indexrelid
where not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
order by o.relname, ic.relname;
\echo ''

\echo '-- ── Row level security ──────────────────────────────────────'
select format('alter table public.%I %s row level security;', o.relname,
       case when c.relrowsecurity then 'enable' else 'disable' end)
       || case when c.relforcerowsecurity then format(E'\nalter table public.%I force row level security;', o.relname) else '' end
from :own_objects o join pg_class c on c.oid = o.oid
where o.relkind in ('r', 'p')
order by o.relname;
\echo ''

\echo '-- ── Policies ────────────────────────────────────────────────'
select format('create policy %I on public.%I as %s for %s to %s%s%s;',
       p.policyname, p.tablename, lower(p.permissive), lower(p.cmd),
       array_to_string(p.roles, ', '),
       coalesce(' using (' || p.qual || ')', ''),
       coalesce(' with check (' || p.with_check || ')', ''))
from pg_policies p
where p.schemaname = 'public'
order by p.tablename, p.policyname;
\echo ''

\echo '-- ── Functions ───────────────────────────────────────────────'
select pg_get_functiondef(p.oid) || E';\n'
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public'
  and p.prokind in ('f', 'p')
  and not exists (
    select 1 from pg_depend d
    where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e'
  )
order by p.proname, pg_get_function_identity_arguments(p.oid);

\echo '-- ── Views ───────────────────────────────────────────────────'
select format(E'create view public.%I%s as\n%s\n', o.relname,
       coalesce(' with (' || array_to_string(c.reloptions, ', ') || ')', ''),
       pg_get_viewdef(o.oid, true))
from :own_objects o join pg_class c on c.oid = o.oid
where o.relkind = 'v'
order by o.relname;

\echo '-- ── Triggers ────────────────────────────────────────────────'
select pg_get_triggerdef(t.oid, true) || ';'
from pg_trigger t
join :own_objects o on o.oid = t.tgrelid
where not t.tgisinternal
order by o.relname, t.tgname;
\echo ''

\echo '-- ── Table and view grants (Supabase API roles) ──────────────'
select format('grant %s on public.%I to %s;',
       string_agg(lower(acl.privilege_type), ', ' order by acl.privilege_type),
       o.relname, r.rolname)
from :own_objects o
join pg_class c on c.oid = o.oid
cross join lateral aclexplode(coalesce(c.relacl, acldefault('r', c.relowner))) acl
join pg_roles r on r.oid = acl.grantee
where o.relkind in ('r', 'p', 'v')
  and r.rolname in ('anon', 'authenticated', 'service_role')
group by o.relname, r.rolname
order by o.relname, r.rolname;
\echo ''

\echo '-- ── Function execute grants (Supabase API roles) ────────────'
select format('grant execute on function public.%I(%s) to %s;',
       p.proname, pg_get_function_identity_arguments(p.oid),
       coalesce(r.rolname, 'public'))
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) acl
left join pg_roles r on r.oid = acl.grantee
where n.nspname = 'public'
  and p.prokind in ('f', 'p')
  and (r.rolname in ('anon', 'authenticated', 'service_role') or acl.grantee = 0)
  and not exists (
    select 1 from pg_depend d
    where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e'
  )
order by p.proname, coalesce(r.rolname, 'public');
